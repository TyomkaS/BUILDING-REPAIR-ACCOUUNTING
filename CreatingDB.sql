CREATE TABLE MaterialssueLog
(
	LogNumber INT IDENTITY(1,1),
	LogDate  DATE,
	MaterialID INT,
	Unit_of_Measure nvarchar(25),
	Quantity real,
	Price_per_Unit money,
	[Sum] money,
	ConsigneeContractorID INT,
	OrderNumber INT,
	OrderDate DATE,

	FOREIGN KEY (OrderNumber,OrderDate) REFERENCES OrdersMain (OrderNumber,OrderDate),
	FOREIGN KEY (MaterialID) REFERENCES Materials (MaterialID),
	FOREIGN KEY (ConsigneeContractorID) REFERENCES Contractors (ContractorID)

);

CREATE TABLE CalculationMaterialList
(
	CalcNumber INT,
	CalcType nvarchar(10),
	BiginDate	DATE,
	EndDate		DATE,
	MaterialSum money,
	PRIMARY KEY(CalcNumber, CalcType)
);


CREATE TABLE CalculationMaterialListDetails
(
	CalcNumber INT,
	CalcType nvarchar(10),
	MaterialID INT,
	Unit_of_Measure_in_CML nvarchar(25),
	Quantity real,
	Price_per_Unit_Of_Measure money,
	OrdersData nvarchar(170),


	FOREIGN KEY (CalcNumber, CalcType)REFERENCES CalculationMaterialList (CalcNumber, CalcType) ON DELETE SET NULL
																								ON UPDATE CASCADE,

	FOREIGN KEY (MaterialID) REFERENCES Materials (MaterialID) ON UPDATE CASCADE
);